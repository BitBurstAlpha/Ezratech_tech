/* eslint-disable @typescript-eslint/no-require-imports -- Reuse the isolated TypeScript test loader. */
require('./test-outcomes.cjs');
const assert = require('node:assert/strict');
const { mockSMEWorkspaces, updateWorkspace, workspaceList, workspaceCounts, northstarWorkspace } = require('../components/sme/workspace/workspace-manager-data.ts');
const { loadDemoScenario, defaultDemoSnapshot } = require('../lib/demo-state.ts');
const { progressReducer } = require('../components/student/progress/progress-state.ts');
let records = structuredClone(mockSMEWorkspaces);
const alex = loadDemoScenario('project-blocker').progress;
assert.deepEqual(workspaceCounts(workspaceList(records, alex)), { active: 2, prestart: 1, attention: 1, completed: 3 });
assert.equal(northstarWorkspace(defaultDemoSnapshot().progress), null);
let accepted = loadDemoScenario('student-project-ready').progress;
accepted = progressReducer(accepted, { type: 'submitInterest' });
accepted = progressReducer(accepted, { type: 'smeAcceptCandidate' });
assert.equal(northstarWorkspace(accepted).status, 'prestart', 'candidate acceptance activates canonical workspace entry');
const danielBefore = JSON.stringify(records['inventory-reporting-improvement']);
const alexBefore = JSON.stringify(alex);
records = updateWorkspace(records, { type: 'task', projectId: 'customer-feedback-analysis', taskId: 'summary', status: 'Completed' });
assert.equal(records['customer-feedback-analysis'].progress, 85);
assert.equal(JSON.stringify(records['inventory-reporting-improvement']), danielBefore);
assert.equal(JSON.stringify(alex), alexBefore);
records = updateWorkspace(records, { type: 'message', projectId: 'customer-feedback-analysis', author: 'Sarah Collins', text: 'Emma-only response' });
assert.equal(records['customer-feedback-analysis'].messages.at(-1).text, 'Emma-only response');
assert(!records['inventory-reporting-improvement'].messages.some(message => message.text === 'Emma-only response'));
assert(!alex.workspace.messages.some(message => message.text === 'Emma-only response'));
records = updateWorkspace(records, { type: 'setup', projectId: 'inventory-reporting-improvement', key: 'agreement', value: true });
assert.equal(records['inventory-reporting-improvement'].status, 'prestart');
records = updateWorkspace(records, { type: 'setup', projectId: 'inventory-reporting-improvement', key: 'data', value: true });
assert.equal(records['inventory-reporting-improvement'].status, 'active');
records = updateWorkspace(records, { type: 'status', projectId: 'customer-feedback-analysis', status: 'paused' });
assert.equal(updateWorkspace(records, { type: 'task', projectId: 'customer-feedback-analysis', taskId: 'summary', status: 'Not Started' }), records);
records = updateWorkspace(records, { type: 'message', projectId: 'customer-feedback-analysis', author: 'Sarah Collins', text: 'Paused clarification' });
assert.equal(records['customer-feedback-analysis'].messages.at(-1).text, 'Paused clarification');
records = updateWorkspace(records, { type: 'status', projectId: 'customer-feedback-analysis', status: 'cancelled' });
assert.equal(updateWorkspace(records, { type: 'file', projectId: 'customer-feedback-analysis', name: 'project-update.pdf', author: 'Sarah' }), records);
assert.equal(updateWorkspace(records, { type: 'message', projectId: 'customer-feedback-analysis', author: 'Sarah', text: 'Blocked' }), records);
assert.equal(updateWorkspace(records, { type: 'task', projectId: 'monthly-reporting-review', taskId: 'monthly-reporting-review-delivery', status: 'Not Started' }), records);
assert.equal(updateWorkspace(records, { type: 'message', projectId: 'northstar-sales-analysis', author: 'Sarah', text: 'Wrong storage' }), records);
assert.equal(workspaceList({}, defaultDemoSnapshot().progress).length, 0);
assert.equal(northstarWorkspace(loadDemoScenario('cancelled-project').progress).status, 'cancelled');
assert.equal(northstarWorkspace(loadDemoScenario('verified-experience').progress).status, 'completed');
assert.deepEqual(JSON.parse(JSON.stringify(records)), records);
console.log('Workspace checks passed: dynamic counts, candidate activation, separate tasks/progress/messages/files/setup, paused messaging, closed read-only, empty state and persistence.');
