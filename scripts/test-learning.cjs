/* eslint-disable @typescript-eslint/no-require-imports -- Reuse the isolated CommonJS TypeScript test loader. */
require('./test-outcomes.cjs');
const assert = require('node:assert/strict');
const { loadDemoScenario, defaultDemoSnapshot, clearEzraTechDemoStorage } = require('../lib/demo-state.ts');
const { demoStorageKey, readDemoStateField, saveDemoStateField } = require('../lib/demo-storage.ts');
const { progressReducer, learningActivityStatus, learningProgress, learningComplete, readinessAccessible, projectsAccessible, workspaceAccessible, workspacePrerequisites } = require('../components/student/progress/progress-state.ts');
const { mockReassessment } = require('../components/student/assessment/development/development-data.ts');
const { preStartChecklist } = require('../components/student/applications/pre-start/pre-start-data.ts');
const { smeResponsibilities } = require('../components/sme/setup/setup-data.ts');
const values = new Map([['unrelated-app', 'preserve']]);
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), get length() { return values.size; }, key: index => [...values.keys()][index], removeItem: key => values.delete(key) };
let state = loadDemoScenario('student-development-needed').progress;
function act(action) { state = progressReducer(state, action); saveDemoStateField(storage, 'progress', state); return state; }
function refresh() { state = readDemoStateField(storage, 'progress', defaultDemoSnapshot().progress); }
assert.equal(learningProgress(state), 0);
assert.equal(readinessAccessible(state), false);
assert.equal(projectsAccessible(state), false);
assert.equal(workspaceAccessible(state), false);
for (const [index, id] of ['planning', 'communication', 'updates'].entries()) {
 assert.equal(learningActivityStatus(state, id), 'not_started');
 act({ type: 'startActivity', id }); refresh();
 assert.equal(learningActivityStatus(state, id), 'in_progress');
 act({ type: 'completeActivity', id }); refresh();
 assert.equal(learningActivityStatus(state, id), 'completed');
 assert.equal(learningProgress(state), [33, 67, 100][index]);
 assert.equal(state.completedActivities.length, index + 1);
 act({ type: 'startActivity', id }); act({ type: 'completeActivity', id }); refresh();
 assert.equal(learningProgress(state), [33, 67, 100][index], 'reviewing/recompleting never duplicates an activity');
 assert.equal(projectsAccessible(state), false); assert.equal(workspaceAccessible(state), false);
}
assert.equal(learningComplete(state), true);
assert.equal(readinessAccessible(state), false, 'learning unlocks reassessment, not readiness');
assert.equal(state.assessment.reassessment.status, 'not_started');
assert.equal(progressReducer(state, { type: 'completeReadiness' }), state, 'cannot skip reassessment');
act({ type: 'setReassessmentAnswers', patch: { delivery: mockReassessment.deliveryOptions[0], communication: mockReassessment.communicationOptions[0], planning: [mockReassessment.planningOptions[4]] } });
act({ type: 'submitReassessment' }); refresh();
assert.equal(state.assessment.reassessment.status, 'more_practice');
assert.equal(readinessAccessible(state), false);
assert.equal(projectsAccessible(state), false);
act({ type: 'completeReassessmentPractice' });
act({ type: 'setReassessmentAnswers', patch: { delivery: mockReassessment.deliveryOptions[1], communication: mockReassessment.communicationOptions[1], planning: mockReassessment.planningOptions.slice(0, 4) } });
act({ type: 'submitReassessment' }); refresh();
assert.equal(state.assessment.reassessment.status, 'completed');
assert.equal(readinessAccessible(state), true);
assert.equal(projectsAccessible(state), false, 'reassessment alone does not unlock Projects');
assert.equal(workspaceAccessible(state), false);
assert.equal(learningProgress({ ...state, completedActivities: ['planning', 'planning', 'communication', 'unknown'] }), 67, 'count only distinct required activities');
act({ type: 'completeReadiness' }); refresh();
assert.equal(state.projectReady, true); assert.equal(projectsAccessible(state), true);
assert.equal(workspaceAccessible(state), false);
const beforeInterest = state;
assert.equal(progressReducer(state, { type: 'smeAcceptCandidate' }), beforeInterest, 'SME acceptance cannot invent interest or completed learning');
act({ type: 'submitInterest' }); refresh();
assert.equal(state.interestSubmitted, true); assert.equal(workspaceAccessible(state), false);
act({ type: 'smeAcceptCandidate' }); refresh();
assert.equal(state.applicationStatus, 'sme_accepted'); assert.equal(workspaceAccessible(state), false);
assert.equal(state.completedActivities.length, 3);
assert.equal(state.assessment.reassessment.status, 'completed', 'SME acceptance preserves earned reassessment');
for (const { key } of preStartChecklist) { act({ type: 'setPreStart', key, value: true }); refresh(); assert.equal(workspaceAccessible(state), false, 'student checks alone do not unlock workspace'); }
act({ type: 'setSMEResponsibilities', values: [...smeResponsibilities] }); refresh();
assert.equal(workspaceAccessible(state), false);
act({ type: 'confirmSMEReadiness' }); refresh();
assert.equal(state.preStart.workspaceUnlocked, true); assert.equal(workspaceAccessible(state), true);
assert.equal(workspacePrerequisites(state), true);
for (const patch of [{ projectReady: false }, { interestSubmitted: false }, { applicationStatus: 'sme_review' }]) assert.equal(workspacePrerequisites({ ...state, ...patch }), false, 'unlock transitions require every project-start condition');
assert.equal(projectsAccessible({ ...defaultDemoSnapshot().progress, projectReady: true }), true, 'marketplace guards read only the canonical ready flag');
assert.equal(workspaceAccessible({ ...defaultDemoSnapshot().progress, preStart: { ...defaultDemoSnapshot().progress.preStart, workspaceUnlocked: true } }), true, 'workspace guards read only the canonical unlock flag');
assert.equal(workspaceAccessible({ ...state, preStart: { ...state.preStart, workspaceUnlocked: false } }), false);
act({ type: 'setPreStart', key: 'studentConfirmed', value: false }); refresh();
assert.equal(state.preStart.workspaceUnlocked, false); assert.equal(workspaceAccessible(state), false);
const fresh = defaultDemoSnapshot().progress;
assert.equal(progressReducer(fresh, { type: 'completeReadiness' }), fresh);
assert.equal(progressReducer(fresh, { type: 'smeAcceptCandidate' }), fresh);
saveDemoStateField(storage, 'project:review', { status: 'approved', matchingUnlocked: true });
saveDemoStateField(storage, 'progress', state); refresh();
assert.deepEqual(readDemoStateField(storage, 'project:review', {}), { status: 'approved', matchingUnlocked: true }, 'provider writes do not replace other providers in the shared record');
clearEzraTechDemoStorage(storage);
assert.equal(storage.getItem(demoStorageKey), null); assert.equal(storage.getItem('unrelated-app'), 'preserve');
assert.equal(learningProgress(readDemoStateField(storage, 'progress', fresh)), 0);
storage.setItem(demoStorageKey, 'invalid JSON'); assert.deepEqual(readDemoStateField(storage, 'progress', fresh), fresh);
console.log('Learning checks passed: 0/33/67/100%, all activity states, refresh persistence, readiness, interest/acceptance, mutual pre-start gates and safe reset.');
