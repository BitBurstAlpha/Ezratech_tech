/* eslint-disable @typescript-eslint/no-require-imports -- Reuse the isolated TypeScript test loader. */
require('./test-outcomes.cjs');
const assert = require('node:assert/strict');
const { loadDemoScenario } = require('../lib/demo-state.ts');
const { progressReducer } = require('../components/student/progress/progress-state.ts');
const { monitoringValues } = require('../components/admin/monitoring/monitoring-data.ts');
const { mockSMEWorkspaces, updateWorkspace, workspaceList } = require('../components/sme/workspace/workspace-manager-data.ts');
const { totalSMEUnread, filterProjectConversations, conversationMilestone } = require('../components/sme/messages/conversation-data.ts');
let alex = loadDemoScenario('project-blocker').progress;
let records = structuredClone(mockSMEWorkspaces);
assert.equal(totalSMEUnread(workspaceList(records, alex)), 3);
alex = progressReducer(alex, { type: 'readProjectMessages', reader: 'sme' });
assert.equal(totalSMEUnread(workspaceList(records, alex)), 2);
alex = progressReducer(alex, { type: 'sendWorkspaceMessage', author: 'Sarah Collins', text: 'Home & Living is the correct category.', attachment: 'updated-sales-data.xlsx' });
assert.equal(alex.workspace.messages.at(-1).senderRole, 'sme');
assert.equal(alex.workspace.messages.at(-1).senderId, 'sarah-collins');
assert.equal(alex.workspace.messages.at(-1).projectId, 'northstar-sales-analysis');
assert.equal(alex.workspace.messages.at(-1).attachment, 'updated-sales-data.xlsx');
assert.equal(monitoringValues(alex).openBlockers, 1);
alex = progressReducer(alex, { type: 'resolveBlocker' });
assert.equal(monitoringValues(alex).openBlockers, 0);
assert.equal(monitoringValues(alex).openIssues, 0);
const alexBefore = JSON.stringify(alex);
records = updateWorkspace(records, { type: 'read', projectId: 'customer-feedback-analysis', reader: 'sme' });
assert.equal(totalSMEUnread(workspaceList(records, alex)), 0);
records = updateWorkspace(records, { type: 'message', projectId: 'customer-feedback-analysis', author: 'Sarah Collins', text: 'Emma-only attachment', attachment: 'recommendations-draft.docx' });
const emma = records['customer-feedback-analysis'];
assert.equal(emma.messages.at(-1).conversationId, emma.messages[0].conversationId);
assert.equal(emma.messages.at(-1).projectId, 'customer-feedback-analysis');
assert.equal(emma.unread.student, 1);
assert.equal(conversationMilestone(emma), 'Insight Summary');
assert.equal(updateWorkspace(records, { type: 'message', projectId: 'customer-feedback-analysis', author: 'Sarah', text: 'Bad attachment', attachment: 'updated-sales-data.xlsx' }), records);
records = updateWorkspace(records, { type: 'message', projectId: 'inventory-reporting-improvement', author: 'Sarah Collins', text: 'Pre-start clarification', attachment: 'inventory-sample.xlsx' });
assert.equal(records['inventory-reporting-improvement'].messages.at(-1).text, 'Pre-start clarification');
assert.equal(records['inventory-reporting-improvement'].status, 'prestart');
records = updateWorkspace(records, { type: 'message', projectId: 'customer-feedback-analysis', author: 'Emma Clarke', senderRole: 'student', text: 'Student-only reply' });
assert.equal(records['customer-feedback-analysis'].messages.at(-1).senderRole, 'student');
assert.equal(records['customer-feedback-analysis'].unread.sme, 1);
assert.equal(records['inventory-reporting-improvement'].messages.some(message => message.text === 'Student-only reply'), false);
assert.equal(JSON.stringify(alex), alexBefore);
assert.equal(filterProjectConversations(workspaceList(records, alex), 'All', 'Emma', 'all').every(project => project.student === 'Emma Clarke'), true);
assert.equal(filterProjectConversations(workspaceList(records, alex), 'All', 'Student-only reply', 'all').length, 1);
assert.equal(filterProjectConversations(workspaceList(records, alex), 'Pre-start', '', 'all').length, 1);
assert.equal(filterProjectConversations(workspaceList(records, alex), 'Completed', '', 'all').length, 3);
assert.equal(filterProjectConversations(workspaceList(records, alex), 'All', '', 'inventory-reporting-improvement').length, 1);
const closed = loadDemoScenario('cancelled-project').progress;
assert.equal(progressReducer(closed, { type: 'sendWorkspaceMessage', author: 'Sarah Collins', text: 'Blocked' }), closed);
assert.deepEqual(JSON.parse(JSON.stringify(records)), records);
const { readDemoStateField, demoStorageKey } = require('../lib/demo-storage.ts');
assert.deepEqual(readDemoStateField({ getItem: key => key === demoStorageKey ? JSON.stringify({ 'sme:workspaces': {} }) : null }, 'sme:workspaces', mockSMEWorkspaces, { objectMap: true }), {}, 'an empty workspace map persists without reseeding unrelated students');
console.log('SME messaging checks passed: shared unread/read, Alex reply/attachment/issue resolution, per-project conversations, pre-start messages, student reply isolation, filters and persistence.');
