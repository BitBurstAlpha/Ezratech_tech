/* eslint-disable @typescript-eslint/no-require-imports -- Reuse the isolated CommonJS TypeScript test loader. */
require('./test-outcomes.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { demoScenarios, loadDemoScenario, defaultDemoSnapshot, clearEzraTechDemoStorage, currentDemoSummary, adminDemoCredentials } = require('../lib/demo-state.ts');
const { demoRouteGroups } = require('../components/demo/demo-data.ts');
const { progressReducer, projectsAccessible, learningComplete } = require('../components/student/progress/progress-state.ts');
const { reassessmentAvailable, assessmentStage } = require('../components/student/assessment/development/development-data.ts');
const { projectCancelled } = require('../components/projects/closure/closure-data.ts');
const { monitoringValues } = require('../components/admin/monitoring/monitoring-data.ts');
const { projectSetupComplete } = require('../components/student/applications/pre-start/pre-start-data.ts');
const { studentOutcome, pilotReport } = require('../components/admin/outcomes/outcomes-data.ts');
const { submissionReady } = require('../components/student/workspace/completion/completion-data.ts');
const baseline = defaultDemoSnapshot();
assert.equal(baseline.progress.studentRegistered, false);
assert.equal(baseline.progress.profileComplete, false);
assert.equal(baseline.progress.assessmentComplete, false);
assert.equal(baseline.progress.projectReady, false);
assert.equal(baseline.progress.preStart.workspaceUnlocked, false);
assert.equal(baseline.review.status, 'approved');
assert.equal(baseline.review.matchingUnlocked, true);
assert.equal(baseline.progress.matchingAvailability.waitlistStatus, 'inactive');
assert.equal(monitoringValues(baseline.progress).openIssues, 0);
assert.equal(Object.fromEntries(currentDemoSummary(baseline.progress, baseline.review)).Project, 'Not Started');
assert.equal(demoScenarios.length, 14);
for (const scenario of demoScenarios) {
 const state = loadDemoScenario(scenario.id);
 assert(fs.existsSync(path.join(__dirname, '..', 'app', scenario.route, 'page.tsx')), `scenario route ${scenario.route}`);
 assert.equal(projectCancelled(state.progress), scenario.stage === 'cancelled');
 if (state.progress.preStart.workspaceUnlocked) {
  assert.equal(projectsAccessible(state.progress), true, `earned access: ${scenario.id}`);
  assert.equal(projectSetupComplete(state.progress.preStart), true, `mutual confirmation: ${scenario.id}`);
  assert.equal(state.progress.applicationStatus, 'sme_accepted');
  assert.equal(state.review.status, 'approved');
  assert.equal(state.review.matchingUnlocked, !projectCancelled(state.progress));
 }
 if (state.progress.verifiedExperience) {
  assert.equal(state.progress.projectCompletion.smeApproved, true);
  assert.equal(state.progress.capabilityReview.status, 'approved');
 }
 const loadedAgain = loadDemoScenario(scenario.id);
 state.progress.completedActivities.push('test-only');
 assert(!loadedAgain.progress.completedActivities.includes('test-only'), 'scenario seeds are independent deep copies');
 const replaced = progressReducer(loadDemoScenario('cancelled-project').progress, { type: 'replaceDemoProgress', progress: loadedAgain.progress });
 assert.deepEqual(replaced, loadedAgain.progress, 'each scenario fully replaces stale cancellation and outcome state');
}
const load = id => loadDemoScenario(id).progress;
const development = load('student-development-needed');
assert.equal(assessmentStage(development), 'development_needed');
assert.equal(learningComplete(development), false);
assert.equal(reassessmentAvailable(development), false);
assert.equal(projectsAccessible(development), false);
assert.equal(projectsAccessible(load('student-project-ready')), true);
const unmatched = load('no-suitable-project');
assert.equal(unmatched.matchingAvailability.supply, 'no_match');
assert.equal(unmatched.matchingAvailability.waitlistStatus, 'inactive');
assert.equal(loadDemoScenario('sme-awaiting-review').review.status, 'under_review');
assert.equal(loadDemoScenario('sme-awaiting-review').review.matchingUnlocked, false);
assert.equal(loadDemoScenario('approved-project-matching').review.matchingUnlocked, true);
const active = monitoringValues(load('active-project'));
assert.equal(active.progress, 30); assert.equal(active.week, 2); assert.equal(active.status, 'On Track');
const blocker = monitoringValues(load('project-blocker'));
assert.equal(blocker.openBlockers, 1); assert.equal(blocker.status, 'Needs Attention');
assert.equal(monitoringValues(load('escalated-issue')).issues[0].status, 'escalated');
assert.equal(load('rejected-project').rejectedDemoProject.status, 'rejected');
const cancelled = load('cancelled-project');
assert.equal(cancelled.capabilityReview.status, 'partial_review_required');
assert.equal(cancelled.activeProject, false);
assert.equal(monitoringValues(cancelled).status, 'Cancelled');
assert.equal(progressReducer(cancelled, { type: 'setWorkspaceTask', id: 'cleaning', status: 'Completed' }), cancelled, 'cancelled workspace stays read-only');
assert.equal(load('assessment-review-request').assessmentDispute.status, 'submitted');
const completed = load('completed-capability-review');
assert.equal(completed.projectCompletion.smeApproved, true);
assert.equal(completed.projectCompletion.capabilityReviewReady, true);
assert.equal(completed.capabilityReview.status, 'pending');
assert.equal(completed.verifiedExperience, false);
assert.equal(submissionReady(completed.submission), true);
assert.equal(studentOutcome(load('verified-experience')).verified, true);
assert.equal(pilotReport(load('pilot-outcomes'), true, 'Current Pilot', '2026-04-05', '2026-10-05').totals.followedUp, 9);
for (const group of demoRouteGroups) for (const [, route] of group.routes) assert(fs.existsSync(path.join(__dirname, '..', 'app', route, 'page.tsx')), `shortcut route ${route}`);
const storage = new Map([['ezratech-demo:progress', 'old'], ['ezratech-demo:session', 'old'], ['unrelated-app', 'keep'], ['ezratech-production', 'keep']]);
clearEzraTechDemoStorage({ get length() { return storage.size; }, key: index => [...storage.keys()][index], removeItem: key => storage.delete(key) });
assert.deepEqual([...storage.keys()], ['unrelated-app', 'ezratech-production']);
assert.equal(adminDemoCredentials.email, 'admin@ezratech.demo');
assert.equal(adminDemoCredentials.password, 'Admin123!');
const registered = progressReducer(baseline.progress, { type: 'registerStudent' });
assert.equal(registered.studentRegistered, true);
assert.equal(registered.profileComplete, false);
assert.equal(progressReducer(registered, { type: 'completeOnboarding' }).profileComplete, true);
console.log('Demo checks passed: 14 coherent scenarios, prerequisite gates, scoped storage reset, default state, registration, credentials and all shortcut routes.');
