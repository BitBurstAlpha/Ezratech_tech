/* eslint-disable @typescript-eslint/no-require-imports -- Reuse the isolated TypeScript test loader. */
require('./test-outcomes.cjs');
const assert = require('node:assert/strict');
const { mockSMEProfile, validateSMEStep } = require('../components/sme/sme-data.ts');
const { mockSMEProjectDraft } = require('../components/sme/projects/project-data.ts');
const { loadDemoScenario } = require('../lib/demo-state.ts');
const { companyProfileComplete, companyProfileChecklist, companyCapacity, organisationSupervisor, organisationLocation, profileProjectDraft, editCompanyProfile } = require('../components/sme/profile/profile-data.ts');
const original = structuredClone(mockSMEProfile);
assert.equal(companyProfileComplete(original), true);
for (let step = 0; step < 4; step++) assert.equal(validateSMEStep(original, step), '');
assert.equal(organisationSupervisor(original).name, 'Sarah Collins');
assert.equal(organisationLocation(original), 'London, UK');
const edited = editCompanyProfile(original, { ...original, companyName: 'Forbidden identity change', primaryContact: { firstName: 'Forbidden' }, supportTime: 'More than 2 hours per week', city: 'Manchester', projectAreas: ['Reporting'], workingStyle: 'Hybrid' });
assert.equal(edited.companyName, original.companyName);
assert.deepEqual(edited.primaryContact, original.primaryContact);
assert.equal(edited.supportTime, 'More than 2 hours per week');
assert.equal(organisationLocation(edited), 'Manchester, UK');
const draft = profileProjectDraft(mockSMEProjectDraft, edited);
assert.equal(draft.supervisionTime, edited.supportTime);
assert.equal(draft.supervisor.name, organisationSupervisor(edited).name);
assert.equal(draft.workingStyle, 'Hybrid');
assert.equal(draft.title, mockSMEProjectDraft.title, 'project-specific scope is preserved');
assert.equal(companyProfileComplete({ ...edited, projectAreas: [] }), false);
assert.equal(companyProfileComplete({ ...edited, supportTime: 'Not sure yet' }), false);
assert.equal(companyProfileComplete({ ...edited, supervisesProjects: 'No', supervisor: { name: '', jobTitle: '', email: '' } }), false);
assert(companyProfileChecklist({ ...edited, projectAreas: [] }).some(item => item.label === 'Project Preferences' && !item.complete));
assert.deepEqual(companyCapacity(loadDemoScenario('active-project').progress), { active: 1, maximum: 2, available: 1 });
assert.deepEqual(companyCapacity(loadDemoScenario('verified-experience').progress), { active: 0, maximum: 2, available: 2 });
assert.equal(companyProfileComplete(JSON.parse(JSON.stringify(edited))), true);
assert.deepEqual(original, mockSMEProfile, 'selectors and edits do not mutate the onboarding seed');
console.log('Company profile checks passed: onboarding reuse, edit identity protection, incomplete checklist, creation defaults, project capacity and persistence.');
