/* eslint-disable @typescript-eslint/no-require-imports -- Use the existing prototype test loader. */
require('./test-outcomes.cjs');
const assert = require('node:assert/strict');
const { loadDemoScenario } = require('../lib/demo-state.ts');
const { progressReducer } = require('../components/student/progress/progress-state.ts');
const { salesProjectId } = require('../components/projects/closure/post-project-data.ts');
const { mockSMEWorkspaces, updateWorkspace } = require('../components/sme/workspace/workspace-manager-data.ts');
const { experienceVerified } = require('../components/student/portfolio/evidence-record-data.ts');
const sample = id => loadDemoScenario(id).progress;
let project = sample('active-project');
const act = action => { project = progressReducer(project,action); };
const close = action => act({type:'closure',projectId:salesProjectId,action});
const approved = sample('completed-capability-review');
for (const task of project.workspaceTasks) act({type:'setWorkspaceTask',id:task.id,status:'Completed'});
act({type:'updateSubmission',patch:approved.submission});
act({type:'submitFinalProject'});
assert(project.projectCompletion.finalSubmitted);
close({kind:'evidence'});assert(!project.projectClosure);
for (const file of project.submission.deliverables) act({type:'markFinalDeliverableReviewed',id:file.id});
for (const [key,value] of Object.entries(approved.finalSMEReview.acceptanceCriteria)) act({type:'setFinalCriterion',key,value});
for (const [key,value] of Object.entries(approved.finalSMEReview.feedback)) act({type:'setFinalFeedback',key,value});
act({type:'confirmFinalPortfolioPermissions'});
act({type:'acceptFinalSMEProject'});
assert(project.projectCompletion.smeApproved);
assert(!project.projectCompletion.capabilityReviewReady);
close({kind:'feedback',text:'Alex delivered the dashboard and explained the trends.',materialsReviewed:true,contributionReviewed:true});
close({kind:'confirm'});assert.equal(project.projectClosure.status,'sme_review_pending');
const offer = sample('closure-offer').projectClosure.offer;
close({kind:'offer',offer});
for (const value of ['discussion_requested','declined','interested']) { close({kind:'response',value});assert.equal(project.projectClosure.offerResponse,value); }
close({kind:'evidence'});
close({kind:'recommendation',recommendation:sample('closure-recommendation').projectClosure.recommendation});
assert.equal(project.projectClosure.offer.title,offer.title);
close({kind:'approveRecommendation'});assert(!project.projectClosure.recommendationApproved);
close({kind:'submit'});assert.equal(project.projectClosure.status,'sme_review_pending');
close({kind:'confirm'});assert.equal(project.projectClosure.status,'sme_closure_completed');
close({kind:'submit'});assert.equal(project.projectClosure.status,'student_acknowledgement_pending');
act({type:'approveCapabilityExperience'});assert(!experienceVerified(project));
close({kind:'acknowledge'});assert(project.projectCompletion.capabilityReviewReady && !experienceVerified(project));
close({kind:'approveRecommendation'});assert(project.projectClosure.recommendationApproved);
act({type:'approveCapabilityExperience'});assert(experienceVerified(project));
assert.deepEqual(JSON.parse(JSON.stringify(project.projectClosure)),project.projectClosure);
project = sample('closure-no-opportunity');assert(project.projectClosure.opportunityFeedback.reason);close({kind:'acknowledge'});act({type:'approveCapabilityExperience'});assert(experienceVerified(project));
project = sample('closure-unaccepted');const submission=structuredClone(project.submission);
act({type:'approveFinalProject'});assert(!project.projectCompletion.smeApproved);
close({kind:'reviewException',approve:true});close({kind:'acknowledge'});
assert.equal(project.projectClosure.status,'closure_completed');assert(!project.projectCompletion.smeApproved && !experienceVerified(project));assert.deepEqual(project.submission,submission);
project=sample('closure-unaccepted');close({kind:'reviewException',approve:false});act({type:'resubmitFinalProject'});assert(project.projectCompletion.resubmitted);
let records=structuredClone(mockSMEWorkspaces);
const id='monthly-reporting-review', before=records['inventory-reporting-improvement'];
records=updateWorkspace(records,{type:'closure',projectId:id,action:{kind:'evidence'}});
assert(records[id].projectClosure.completionEvidenceAvailable);
assert.equal(records['inventory-reporting-improvement'],before);assert(!records['customer-feedback-analysis'].projectClosure);
console.log('Project closure passed: submission, acceptance, combinations, private responses, SME confirmation, acknowledgement, independent verification, exceptional review and record isolation.');
